import re
from dataclasses import asdict, dataclass

from code_health.config import DEFAULT_CONFIG, Config, rules_for
from code_health.ignores import Ignore, find_ignores, suppresses
from code_health.languages import language_for_path
from code_health.measure import FileMetrics, measure_file
from code_health.score import SCORER_VERSION, band, score_file
from code_health.smells import (
    FILE,
    FIX_HINTS,
    INVALID_IGNORE,
    NEW_IGNORE,
    Finding,
    find_smells,
)


@dataclass(frozen=True)
class FileReport:
    path: str
    score: float | None
    band: str
    findings: tuple[Finding, ...] = ()
    reason: str | None = None
    ignores: tuple[Ignore, ...] = ()
    ignored: tuple[Ignore, ...] = ()
    digests: tuple[tuple[str, str], ...] = ()
    metrics: FileMetrics | None = None

    def digest_for(self, function: str) -> str:
        return dict(self.digests).get(function, "")


def review_source(
    path: str, source: bytes, config: Config = DEFAULT_CONFIG, match_path: str | None = None
) -> FileReport:
    language = language_for_path(path)
    if language is None:
        return _not_scored(path, "unsupported language")
    if is_generated(source):
        return _not_scored(path, "generated")
    metrics = measure_file(source, language)
    if metrics.parse_errors:
        return _not_scored(path, "parse errors")
    limits, weights = rules_for(config, match_path or path)
    ignores, invalid = find_ignores(source, metrics.functions)
    kept, ignored = _apply_ignores(find_smells(metrics, limits), ignores)
    findings = (*kept, *invalid)
    score = score_file(findings, weights)
    return FileReport(
        path=path,
        score=score,
        band=band(score),
        findings=findings,
        ignores=tuple(ignores),
        ignored=tuple(ignored),
        digests=((FILE, metrics.digest), *((f.name, f.digest) for f in metrics.functions)),
        metrics=metrics,
    )


def _apply_ignores(findings, ignores: list[Ignore]) -> tuple[list[Finding], list[Ignore]]:
    kept, ignored = [], []
    for finding in findings:
        ignore = next((i for i in ignores if suppresses(i, finding)), None)
        if ignore is None:
            kept.append(finding)
        else:
            ignored.append(Ignore(finding.smell, finding.function, finding.line, ignore.reason))
    return kept, ignored


_GENERATED = re.compile(rb"<auto-generated|@generated|\bDO NOT EDIT\b")
_COMMENT_STARTS = (b"//", b"/*", b"*", b"#", b"--", b"<#", b"'")
_HEADER_LIMIT = 10


def is_generated(source: bytes) -> bool:
    return any(_GENERATED.search(line) for line in _header(source))


def _header(source: bytes) -> list[bytes]:
    header = []
    for line in source.lstrip(b"\xef\xbb\xbf").splitlines()[:_HEADER_LIMIT]:
        stripped = line.strip()
        if stripped and not stripped.startswith(_COMMENT_STARTS):
            break
        header.append(stripped)
    return header


def format_score_line(report: FileReport) -> str:
    if report.score is None:
        return f"   -  not scored  {report.path} ({report.reason})"
    return f"{report.score:4.1f}  {report.band:<10}  {report.path}"


def format_review(report: FileReport) -> str:
    if report.score is None:
        return f"{report.path}  not scored ({report.reason})"
    lines = [f"{report.path}  {report.score:.1f}  {report.band}"]
    width = max((len(finding.smell) for finding in report.findings), default=0)
    for finding in report.findings:
        location = f"{finding.function}:{finding.line}"
        lines.append(f"  {finding.smell:<{width}}  {location}  {describe(finding)}")
        lines.append(f"  {'':<{width}}  fix: {FIX_HINTS[finding.smell]}")
    lines += [f"  ~ ignored  {i.smell}  {i.function}:{i.line}  {i.reason}" for i in report.ignored]
    if not report.findings and not report.ignored:
        lines.append("  no findings")
    return "\n".join(lines)


def describe(finding: Finding, suffix: str = "") -> str:
    if note := _NOTES.get(finding.smell):
        return note
    unit = _UNITS[finding.smell]
    measured = f"{unit} {finding.value}" if unit in _UNIT_FIRST else f"{finding.value} {unit}"
    return f"{measured}{suffix} (limit {finding.limit})"


_UNITS = {
    "Complex Method": "complexity",
    "Deep Nested Complexity": "depth",
    "Bumpy Road": "bumps",
    "Complex Conditional": "operators",
    "Large Method": "lines",
    "Excess Function Arguments": "parameters",
    "Large File": "lines",
    "Mocked Own Module": "mocks",
}
_UNIT_FIRST = {"complexity", "depth"}
_NOTES = {
    INVALID_IGNORE: "needs `code-health: ignore <Smell> -- <reason>`",
    NEW_IGNORE: "new ignore comment",
}


def to_json(reports: list[FileReport], include_findings: bool) -> dict:
    return {"scorer_version": SCORER_VERSION, "files": [_file_json(r, include_findings) for r in reports]}


def _file_json(report: FileReport, include_findings: bool) -> dict:
    data = {"path": report.path, "score": report.score, "band": report.band}
    if report.reason:
        data["reason"] = report.reason
    elif include_findings:
        data["findings"] = [
            {**asdict(finding), "fix": FIX_HINTS[finding.smell]} for finding in report.findings
        ]
        data["ignored"] = [asdict(ignore) for ignore in report.ignored]
    return data


def _not_scored(path: str, reason: str) -> FileReport:
    return FileReport(path=path, score=None, band="not scored", reason=reason)
